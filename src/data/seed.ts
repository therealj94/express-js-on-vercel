function slugSeed(index: number): string {
  return `seed-${(index + 1).toString().padStart(3, '0')}`
}

export function buildSeedCompanies(): Company[] {
  const now = new Date().toISOString()
  return raw.map((item, index) => {
    const country = countryBySlug.get(item.countrySlug)
    const city = country?.cities.find((c) => c.slug === item.citySlug)
    const baseLat = city?.lat ?? country?.lat ?? 0
    const baseLng = city?.lng ?? country?.lng ?? 0
    return {
      id: slugSeed(index),
      ownerId: 'seed',
      legalName: item.legalName,
      tradeName: item.tradeName,
      taxId: `RTN-${String(1000 + index)}`,
      categorySlug: item.categorySlug,
      productsServices: item.productsServices,
      countrySlug: item.countrySlug,
      citySlug: item.citySlug,
      address: item.address,
      lat: baseLat + item.jitterLat,
      lng: baseLng + item.jitterLng,
      description: item.description,
      logoDataUrl: null,
      coverDataUrl: null,
      gallery: [],
      socials: item.socials,
      hours: { ...defaultHours, ...item.hoursOverride },
      kyc: {
        status: item.verified ? 'verified' : 'pending',
        documents: [],
        submittedAt: now,
        reviewedAt: item.verified ? now : null,
        note: null,
      },
      verified: item.verified,
      acceptsOrigen: true,
      createdAt: now,
      updatedAt: now,
    }
  })
}
