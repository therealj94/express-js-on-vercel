// Detección del idioma del sistema. Devuelve 'es' o 'en'. Si no se puede
// determinar, cae en 'en'. En iOS y Android tomamos el primer idioma
// preferido del usuario. Se usa la primera vez que abre la app; después
// respetamos la preferencia manual guardada en AsyncStorage.
function idiomaDelSistema() {
  // Vía oficial: expo-localization. Antes se leía NativeModules.SettingsManager
  // (iOS) e I18nManager (Android), módulos del puente legacy que bajo la Nueva
  // Arquitectura pueden venir vacíos. Como la lectura estaba dentro de un
  // try/catch con encadenamiento opcional, no rompía nada: simplemente devolvía
  // 'en' siempre, y un usuario hispanohablante abría la app en inglés sin que
  // nada avisara del fallo.
  try {
    const loc = Localization.getLocales?.()[0];
    const code = loc?.languageCode || loc?.languageTag || null;
    if (code && /^es/i.test(String(code))) return 'es';
    if (code) return 'en';
  } catch (e) {}

  // Respaldo para builds viejas donde el módulo no esté disponible.
  try {
    let loc = null;
    if (Platform.OS === 'ios') {
      loc = NativeModules.SettingsManager?.settings?.AppleLocale
        || NativeModules.SettingsManager?.settings?.AppleLanguages?.[0]
        || null;
    } else if (Platform.OS === 'android') {
      loc = NativeModules.I18nManager?.localeIdentifier || null;
    }
    if (loc && /^es/i.test(String(loc))) return 'es';
  } catch (e) {}
  return 'en';
}

export function LangProvider({ children }) {
  // Por defecto el idioma del sistema — así un usuario en español ve la app
  // en español desde el primer momento, sin tener que ir a Ajustes.
  const [lang, setLangState] = useState(idiomaDelSistema());
  useEffect(() => {
    AsyncStorage.getItem('veta-lang').then((l) => { if (l === 'en' || l === 'es') setLangState(l); }).catch(() => {});
  }, []);
  const setLang = (l) => {
    setLangState(l);
    AsyncStorage.setItem('veta-lang', l).catch(() => {});
  };
  const t = (key, vars) => {
    let s = (S[lang] && S[lang][key]) || S.en[key] || S.es[key] || key;
    // `split`+`join` en vez de `replace`: replace con una cadena sustituye
    // SOLO la primera aparición, así que un texto que nombra la misma
    // variable dos veces salía con el hueco a medio rellenar --se vio en
    // pantalla: "se paga en ORIGEN, no en {s}"--.
    if (vars) for (const k of Object.keys(vars)) s = s.split(`{${k}}`).join(String(vars[k]));
    return s;
  };
  return <LangCtx.Provider value={{ lang, t, setLang }}>{children}</LangCtx.Provider>;
}
