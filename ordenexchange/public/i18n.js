// Idioma actual: recordado, si no el del navegador, si no español.
let IDIOMA = (() => {
  try {
    const g = localStorage.getItem('ordenexchange.idioma');
    if (g === 'es' || g === 'en') return g;
  } catch (_) { /* almacenamiento bloqueado */ }
  const nav = (navigator.language || 'es').toLowerCase();
  return nav.startsWith('en') ? 'en' : 'es';
})();

function t(clave, vars) {
  const dic = I18N[IDIOMA] || I18N.es;
  let s = dic[clave];
  if (s === undefined) s = I18N.es[clave];
  if (s === undefined) return clave;
  if (vars) s = s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] === undefined || vars[k] === null ? '' : String(vars[k])));
  return s;
}

function fijarIdioma(idioma) {
  IDIOMA = idioma === 'en' ? 'en' : 'es';
  try { localStorage.setItem('ordenexchange.idioma', IDIOMA); } catch (_) { /* nada */ }
  document.documentElement.lang = IDIOMA;
}
