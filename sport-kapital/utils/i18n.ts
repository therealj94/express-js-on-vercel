//
// Formato del diccionario: clave → [español, inglés].

export type Lang = 'es' | 'en';

let currentLang: Lang = 'es';
export function setCurrentLang(l: Lang): void {
  if (l === 'es' || l === 'en') currentLang = l;
}
export function getLang(): Lang {
  return currentLang;
}

