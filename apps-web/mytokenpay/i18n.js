// ── el motor ─────────────────────────────────────────────────────────────────
let idiomaActual = (() => {
  try { const g = localStorage.getItem('mtp.idioma'); if (g === 'es' || g === 'en') return g; } catch {}
  return (navigator.language || 'es').toLowerCase().startsWith('es') ? 'es' : 'en';
})();

function t(clave) {
  return I18N[idiomaActual][clave] ?? I18N.es[clave] ?? clave;
}

/* Pinta los textos fijos (data-t / data-tp) y los titulares compuestos, que
   llevan la segunda línea en el degradado de la marca. */
function pintarIdioma() {
  document.documentElement.lang = idiomaActual;
  document.querySelectorAll('[data-t]').forEach(el => { el.innerHTML = t(el.dataset.t); });
  document.querySelectorAll('[data-tp]').forEach(el => { el.placeholder = t(el.dataset.tp); });
  document.querySelectorAll('[data-lang]').forEach(b => {
    b.setAttribute('aria-pressed', String(b.dataset.lang === idiomaActual));
  });
  // El titular de la portada entra palabra a palabra. Se reconstruye al cambiar
  // de idioma para que la entrada se repita: cambiar de idioma es volver a abrir.
  const h = document.getElementById('bv-titulo');
  if (h) {
    const linea = (texto, marcado, base) => '<span class="renglon">' +
      texto.split(' ').map((p, i) =>
        `<span class="palabra" style="animation-delay:${(base + i) * 85 + 200}ms">${marcado ? '<span class="neon">' + p + '</span>' : p}&nbsp;</span>`
      ).join('') + '</span>';
    h.innerHTML = linea(t('bv.t1'), false, 0) + linea(t('bv.t2'), true, t('bv.t1').split(' ').length);
  }
  [['r1-titulo', 'r1'], ['r2-titulo', 'r2'], ['r3-titulo', 'r3'], ['cierre-titulo', 'cierre']].forEach(([id, k]) => {
    const el = document.getElementById(id);
    if (el) el.innerHTML = `${t(k + '.t1')}<br><span class="neon">${t(k + '.t2')}</span>`;
  });
}
